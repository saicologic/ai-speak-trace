import { findContacts, maskContacts } from './contact-patterns';

describe('findContacts', () => {
  it('maskContacts で伏せる文字列を、伏せる前の形で返す', () => {
    expect(
      findContacts('メールは taro@example.com、電話は 090-1234-5678 です'),
    ).toEqual(['taro@example.com', '090-1234-5678']);
  });

  it('連絡先がなければ空', () => {
    expect(findContacts('バージョン 1.2.3 を使う')).toEqual([]);
  });
});

describe('maskContacts', () => {
  it.each([
    ['電話は 090-1234-5678 です', '電話は [電話番号] です'],
    ['電話は 09012345678 です', '電話は [電話番号] です'],
    ['代表は 03-1234-5678', '代表は [電話番号]'],
    ['全角で ０９０－１２３４－５６７８', '全角で [電話番号]'],
    ['海外からは +81-90-1234-5678', '海外からは [電話番号]'],
    ['メールは test.user@example.co.jp へ', 'メールは [メールアドレス] へ'],
    ['カードは 4111 1111 1111 1111', 'カードは [カード番号]'],
    ['番号は 1234-5678-9012', '番号は [マイナンバー]'],
    ['接続先は 192.168.0.1', '接続先は [IPアドレス]'],
    ['電話は 090-1234-5678 2件あります', '電話は [電話番号] 2件あります'],
    ['代表 03-1234-5678 3番へ', '代表 [電話番号] 3番へ'],
    ['2件 090-1234-5678 にかけました', '2件 [電話番号] にかけました'],
    ['3番 03-1234-5678', '3番 [電話番号]'],
    ['メールは taro@例え.日本 へ', 'メールは [メールアドレス] へ'],
    ['メールは taro@例え.jp へ', 'メールは [メールアドレス] へ'],
  ])('%s', (text, expected) => {
    expect(maskContacts(text)).toBe(expected);
  });

  it.each([
    ['2026年10月20日に話しました'],
    ['予算は 1000000 円です'],
    ['バージョン 1.2.3 を使う'],
    ['TypeScript 5.7 に上げた'],
    ['10:30 から 12:00 まで'],
    ['カードの番号に似た 4111 1111 1111 1112'],
    ['999.999.999.999'],
    // 長い番号の一部を電話番号として伏せない
    ['注文番号は 090-1234-5678-9 です'],
    ['注文番号は 0901234567890 です'],
    ['注文番号は 9-090-1234-5678 です'],
  ])('連絡先ではないものは伏せない（%s）', (text) => {
    expect(maskContacts(text)).toBe(text);
  });
});
