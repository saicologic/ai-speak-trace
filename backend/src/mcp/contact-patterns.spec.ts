import { maskContacts } from './contact-patterns';

describe('maskContacts', () => {
  it.each([
    ['電話は 090-1234-5678 です', '電話は [電話番号] です'],
    ['電話は 09012345678 です', '電話は [電話番号] です'],
    ['代表は 03-1234-5678', '代表は [電話番号]'],
    ['全角で ０９０－１２３４－５６７８', '全角で [電話番号]'],
    ['海外からは +81-90-1234-5678', '海外からは [電話番号]'],
    ['メールは test.user@example.co.jp へ', 'メールは [メールアドレス] へ'],
    ['カードは 4111 1111 1111 1111', 'カードは [カード番号]'],
    ['番号は 1234-5678-9012', '番号は [マイナンバー]'],
    ['接続先は 192.168.0.1', '接続先は [IPアドレス]'],
  ])('%s', (text, expected) => {
    expect(maskContacts(text)).toBe(expected);
  });

  it.each([
    ['2026年10月20日に話しました'],
    ['予算は 1000000 円です'],
    ['バージョン 1.2.3 を使う'],
    ['TypeScript 5.7 に上げた'],
    ['10:30 から 12:00 まで'],
    ['カードの番号に似た 4111 1111 1111 1112'],
    ['999.999.999.999'],
  ])('連絡先ではないものは伏せない（%s）', (text) => {
    expect(maskContacts(text)).toBe(text);
  });
});
